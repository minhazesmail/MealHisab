const dictionaries: Record<Locale, Record<DictKey, string>> = { en, bn }

export function t(locale: Locale, key: DictKey): string {
  return dictionaries[locale][key] ?? dictionaries.en[key] ?? key
}

export function createTranslator(locale: Locale) {
  return (key: DictKey) => t(locale, key)
}

const BN_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯']

export function toBanglaDigits(value: string | number): string {
  return String(value).replace(/\d/g, (d) => BN_DIGITS[Number(d)] ?? d)
}

export function formatBdt(amount: number, locale: Locale = 'en'): string {
  const fixed = Number.isFinite(amount) ? amount.toFixed(2) : '0.00'
  const withSep = fixed.replace(/\B(?=(\d{3})+(?!\d))/g, ',')
  const body = locale === 'bn' ? toBanglaDigits(withSep) : withSep
  return `৳${body}`
}

export function formatNumber(n: number, locale: Locale = 'en'): string {
  const s = String(n)
  return locale === 'bn' ? toBanglaDigits(s) : s
}

